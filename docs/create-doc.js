const FONT = "Times New Roman";
const FONT_SIZE_HALF_POINTS = 28; // 14 pt

function body(text, opts = {}) {
  return new Paragraph({
    alignment: opts.center
      ? AlignmentType.CENTER
      : opts.right
        ? AlignmentType.RIGHT
        : AlignmentType.JUSTIFIED,
    spacing: { line: 360, before: 0, after: 0 },
    indent: opts.noIndent || opts.center || opts.right ? {} : { firstLine: 709 }, // 1.25 cm
    children: [
      new TextRun({
        text,
        font: FONT,
        size: FONT_SIZE_HALF_POINTS,
        bold: !!opts.bold,
        italics: !!opts.italic,
      }),
    ],
  });
}

function heading(text, level = HeadingLevel.HEADING_1) {
  return new Paragraph({
    heading: level,
    alignment: AlignmentType.CENTER,
    spacing: { line: 360, before: 240, after: 120 },
    children: [
      new TextRun({
        text,
        font: FONT,
        size: FONT_SIZE_HALF_POINTS,
        bold: true,
      }),
    ],
  });
}

function sourceItem(index, text) {
  return new Paragraph({
    alignment: AlignmentType.JUSTIFIED,
    spacing: { line: 360, before: 0, after: 0 },
    indent: { hanging: 454 }, // hanging indent for bibliography
    children: [
      new TextRun({
        text: `${index}. ${text}`,
        font: FONT,
        size: FONT_SIZE_HALF_POINTS,
      }),
    ],
  });
}

